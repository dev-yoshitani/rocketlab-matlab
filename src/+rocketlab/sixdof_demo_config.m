function p=sixdof_demo_config()
% Synthetic free-flight interval; no real-vehicle values are adopted.
[v,~]=rocketlab.demo_config; v=rocketlab.validate_vehicle(v);
m=v.members.density.*v.members.A.*(v.members.s1-v.members.s0);
mass=[m;1.81-sum(m)]; station=[.25;.75;.4]; I=zeros(3,3,3);
for k=1:2
 ro=v.members.diameter(k)/2; ri=ro-v.members.thickness(k); L=v.members.s1(k)-v.members.s0(k);
 I(:,:,k)=diag([mass(k)*(ro^2+ri^2)/2,repmat(mass(k)*(3*(ro^2+ri^2)+L^2)/12,1,2)]);
end
I(:,:,3)=eye(3)*.4*mass(3)*.03^2;
props=rocketlab.mass_properties(mass,[station,zeros(3,2)],I);
p=struct('id',"DEMO-6DOF-fixed-CG",'source',"synthetic verification inputs; not real-vehicle data", ...
 'vehicle',v,'vehicleHash',rocketlab.hash(jsonencode(v)), ...
 'partIds',["tube-front";"tube-aft";"payload"],'dryPartMass_kg',mass,'partStation_m',station, ...
 'dryPartInertia_S_kgm2',I,'propellantStation_m',props.cg(1), ...
 'propellantInitial_kg',.19,'propellantInertiaPerKg_S_m2',diag([.0002,.000933333333333,.000933333333333]), ...
 'time_s',[0;.1;1.9;2],'thrust_N',[0;150;150;0],'massFlow_kg_s',[0;.1;.1;0], ...
 'thrustStation_m',.8,'cpStation_m',.72, ...
 'aeroMach',[0;.5;1],'aeroCA',[.4;.45;.6],'normalSlope_rad',2,'aeroAngleLimit_rad',.5, ...
 'area_m2',.003,'angularDamping_Nms',[.002;.06;.06], ...
 'windNED_m_s',[2;1;0],'g_m_s2',9.80665,'rho0_kg_m3',1.225,'scaleHeight_m',8500,'soundSpeed_m_s',340, ...
 'position0_NED_m',[0;0;-30],'velocity0_body_m_s',[20;0;0], ...
 'euler0_rad',[.1;pi/2-.05;.2],'omega0_body_rad_s',[.25;.06;-.04], ...
 'stopTime_s',4,'maxStep_s',.01,'relTol',1e-10,'absTol',1e-12, ...
 'scope',"fixed CG; prescribed mass and inertia; free flight only; postburn structural transfer");
p=rocketlab.validate_sixdof(p);
end
