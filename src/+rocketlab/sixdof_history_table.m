function t=sixdof_history_table(h)
t=array2table([h.time_s,h.state,h.mass_kg,h.propellant_kg,h.massFlow_kg_s,h.thrust_N,h.airspeed_m_s,h.mach,h.q_Pa,h.alpha_rad,h.beta_rad,h.quaternionNorm, ...
 h.acceleration_NED_m_s2,h.angularAcceleration_B_rad_s2], ...
 'VariableNames',{'time_s','north_m','east_m','down_m','vn_m_s','ve_m_s','vd_m_s','qw','qx','qy','qz','p_rad_s','q_rad_s','r_rad_s', ...
 'mass_kg','propellant_kg','massFlow_kg_s','thrust_N','airspeed_m_s','mach','dynamicPressure_Pa','alpha_rad','beta_rad','quaternionNorm', ...
 'an_m_s2','ae_m_s2','ad_m_s2','pdot_rad_s2','qdot_rad_s2','rdot_rad_s2'});
extra=array2table([repmat(h.parameters.cgStation_m,numel(h.time_s),1),h.inertia_B_kgm2,h.aeroForce_B_N,h.momentCG_B_Nm], ...
 'VariableNames',{'cgStation_m','Ixx_kgm2','Iyy_kgm2','Izz_kgm2','Ixy_kgm2','Ixz_kgm2','Iyz_kgm2','aeroFx_N','aeroFy_N','aeroFz_N','MxCG_Nm','MyCG_Nm','MzCG_Nm'});
t=[t,extra]; t.structuralEligible=h.structuralEligible;
end
