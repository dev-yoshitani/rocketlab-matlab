function [v,d]=flight_structure_demo(p)
% Explicit synthetic mass/load placement, never inferred from real-vehicle data.
if nargin<1, p=rocketlab.flight_demo_config; end
[v,~]=rocketlab.demo_config; v=rocketlab.validate_vehicle(v);
tubeMass=v.members.density.*v.members.A.*(v.members.s1-v.members.s0);
payload=p.dryMass-sum(tubeMass);
assert(payload>0,'rocketlab:DemoMass','Demo dry mass must exceed the tube mass.');
d=struct('id',"DEMO-axial-load-placement",'vehicleId',v.id,'vehicleHash',rocketlab.hash(jsonencode(v)), ...
 'source',"synthetic demo: fixed body datum, lumped mass, fixed vertical attitude", ...
 'thrustStation_m',.8,'dragStation_m',.15, ...
 'loadPath',"Net thrust enters at the equivalent motor/airframe plane; motor-local stress is excluded.", ...
 'parts',table(["tube-front";"tube-aft";"payload";"propellant"],[.25;.75;.4;.8], ...
 [tubeMass;payload;0],[0;0;0;1], ...
 'VariableNames',{'id','station_m','dryMass_kg','propellantFraction'}));
end
